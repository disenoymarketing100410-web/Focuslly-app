/**
 * Helper para obtener traducciones de forma segura
 * @param {string} lang - 'es' | 'en'
 * @param {string} path - ruta con puntos e.g. 'hero.focusRealm' o clave simple 'home'
 * @param {string} fallback - texto por defecto
 */
export const t = (lang = 'es', path = '', fallback = '') => {
  if (!path) return fallback;
  const currentLang = lang === 'en' ? 'en' : 'es';
  const dict = TRANSLATIONS[currentLang];
  
  // Si la clave existe directamente en la raíz
  if (dict[path] !== undefined && typeof dict[path] === 'string') {
    return dict[path];
  }

  // Buscar por ruta anidada e.g. 'hero.focusRealm'
  const parts = path.split('.');
  let current = dict;
  for (const part of parts) {
    if (current && current[part] !== undefined) {
      current = current[part];
    } else {
      // Intentar en español como respaldo
      let fallbackVal = TRANSLATIONS['es'];
      for (const p of parts) {
        if (fallbackVal && fallbackVal[p] !== undefined) {
          fallbackVal = fallbackVal[p];
        } else {
          fallbackVal = null;
          break;
        }
      }
      return typeof fallbackVal === 'string' ? fallbackVal : (fallback || path);
    }
  }

  return typeof current === 'string' ? current : (fallback || path);
};
